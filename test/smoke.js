'use strict';
const assert = require('assert');
const { TestClient, OP } = require('./client');
const url = process.argv[2] || 'ws://127.0.0.1:8090/ws';
(async () => {
  const c = new TestClient(url); await c.open();
  await c.wait(OP.CONNECT);
  const email = 't' + Date.now() + '@example.com';
  c.send(OP.ACCOUNT_EMAIL_CODE_REQUEST, { email, purpose: 'register', requestId: 'r1' });
  const code = await c.wait(OP.ACCOUNT_EMAIL_CODE_RESULT);
  console.log('code result', code.data);
  const m = /(\d{6})/.exec(code.data.message);
  c.send(OP.ACCOUNT_REGISTER, { email, password: 'password123', code: m[1], purpose: 'register', requestId: 'r2' });
  console.log('register', (await c.wait(OP.ACCOUNT_REGISTER_RESULT)).data);
  c.send(OP.LOGIN, { username: email, password: 'password123' });
  const l1 = await c.wait(OP.LOGIN_SUCCESS);
  assert(l1.data.requiresCharacterCreation);
  c.send(OP.CHARACTER_CREATE, { nickname: 'T' + String(Date.now()).slice(-6), appearance: { gender: 'man' } });
  console.log('create', (await c.wait(OP.CHARACTER_CREATE_RESULT)).data);
  const l2 = await c.wait(OP.LOGIN_SUCCESS);
  console.log('login', l2.data.playerId, l2.data.mapRef, l2.data.x, l2.data.y, 'enemies', l2.data.enemies.length);
  c.send(OP.ITEM_QUERY, {});
  const st = await c.wait(OP.ITEM_STATE);
  console.log('items', st.data.inventory.slots.filter(Boolean).map((i) => i.name + 'x' + i.count), st.data.params.progression);
  c.send(OP.HEARTBEAT, { clientTime: Date.now(), seq: 1 });
  console.log('timesync', (await c.wait(OP.TIME_SYNC)).data);
  c.send(OP.ACTION, { action: { type: 'move', x: l2.data.x + 48, y: l2.data.y, z: 0, seq: 1, timestamp: Date.now() } });
  const mu = await c.wait(OP.MOVE_UPDATE, (d) => d.players.some((p) => p.playerId === l2.data.playerId));
  console.log('move update', JSON.stringify(mu.data.players[0]).slice(0, 300));
  c.send(OP.MAP_SWITCH, { mapRef: 'hunt_p_01', clientSeq: 1 });
  const ms = await c.wait(OP.MAP_SWITCH_RESULT);
  console.log('switch', ms.data.success, ms.data.message, ms.data.mapRef, (ms.data.enemies || []).length);
  c.send(OP.SHOP_QUERY, { kind: 'tools' });
  const shop = await c.wait(OP.SHOP_STATE);
  console.log('shop tabs', Object.fromEntries(Object.entries(shop.data.tabs).map(([k, v]) => [k, v.length])));
  c.send(OP.SHOP_BUY, { kind: 'tools', itemId: 72, count: 2 });
  const d = await c.wait(OP.ITEM_DELTA);
  console.log('buy delta', d.data.changes.map((x) => x.type + ':' + (x.item ? x.item.name + 'x' + x.item.count : '')), d.data.changes.find((x) => x.params).params.profile.gold);
  c.close();
  process.exit(0);
})().catch((e) => { console.error('FAIL', e); process.exit(1); });
